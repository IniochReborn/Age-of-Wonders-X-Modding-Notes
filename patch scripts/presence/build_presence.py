#!/usr/bin/env python3
r"""
Build AoWxPresence.exe (Discord Rich Presence helper, 2026-10-21).

Compiles patch scripts\presence\AoWxPresence\*.cs with the in-box .NET Framework 4 compiler (C# 5) as an x86 winexe
(x86 so it can enumerate the 32-bit game's modules).  The Discord Application ID is baked in as ClientId.cs.

Outputs patch scripts\presence\build\AoWxPresence.exe and (unless --no-copy) a copy in the game root.

Usage: py -3.10 build_presence.py --client-id <Discord APPLICATION ID> [--no-copy]
       (the id is remembered in client_id.txt next to this script, so later builds can omit it)
"""
import argparse, os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, "AoWxPresence")
CSC = r"C:\Windows\Microsoft.NET\Framework\v4.0.30319\csc.exe"
ICON = os.path.join(GAME, "patch scripts", "installer", "assets", "aowx.ico")
ID_FILE = os.path.join(HERE, "client_id.txt")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--client-id")
    ap.add_argument("--out", default=os.path.join(HERE, "build", "AoWxPresence.exe"))
    ap.add_argument("--no-copy", action="store_true")
    a = ap.parse_args()
    cid = a.client_id or (open(ID_FILE).read().strip() if os.path.exists(ID_FILE) else "")
    if not re.fullmatch(r"\d{15,22}", cid or ""):
        print("need --client-id <Discord APPLICATION ID> (digits)"); return 1
    open(ID_FILE, "w").write(cid + "\n")
    with open(os.path.join(SRC, "ClientId.cs"), "w", encoding="utf-8") as f:
        f.write("// GENERATED by build_presence.py - do not edit\n")
        f.write("namespace AoWxPresence { internal static class ClientId { internal const string Value = \"%s\"; } }\n" % cid)
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    cmd = [CSC, "/nologo", "/target:winexe", "/optimize+", "/platform:x86", "/out:" + a.out, "/r:System.dll", "/r:System.Core.dll"]
    if os.path.isfile(ICON):
        cmd.append("/win32icon:" + ICON)
    cmd += [os.path.join(SRC, f) for f in sorted(os.listdir(SRC)) if f.endswith(".cs")]
    r = subprocess.run(cmd, capture_output=True, text=True)
    print((r.stdout + r.stderr).strip())
    if r.returncode != 0:
        print("!! csc failed"); return 1
    print("built " + a.out + " (%d bytes)" % os.path.getsize(a.out))
    if not a.no_copy:
        dst = os.path.join(GAME, "AoWxPresence.exe")
        shutil.copy2(a.out, dst)
        print("copied -> " + dst)
    return 0


if __name__ == "__main__":
    sys.exit(main())
