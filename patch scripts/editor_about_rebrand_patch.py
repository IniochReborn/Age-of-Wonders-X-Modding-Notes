def apply(buf: bytearray):
    for off, old, new, desc in BYTE_PATCHES:
        cur = bytes(buf[off:off+len(old)])
        if cur == new:
            print(f"  [skip] 0x{off:X} already patched ({desc})")
            continue
        assert cur == old, f"OLD mismatch @0x{off:X}: expected {old.hex()} got {cur.hex()} ({desc})"
        buf[off:off+len(new)] = new
        print(f"  [ok]   0x{off:X} {old.hex()} -> {new.hex()} ({desc})")
    # append relocated DFM
    if len(buf) == APPEND_OFF:
        assert len(DFM) == 2560, f"DFM blob len {len(DFM)} != 2560"
        buf += DFM
        print(f"  [ok]   appended DFM @0x{APPEND_OFF:X} ({len(DFM)}B), new EOF 0x{len(buf):X}")
    elif len(buf) >= APPEND_OFF + len(DFM) and bytes(buf[APPEND_OFF:APPEND_OFF+len(DFM)]) == DFM:
        print(f"  [skip] DFM already appended @0x{APPEND_OFF:X}")
    else:
        raise AssertionError(f"unexpected file size 0x{len(buf):X}; expected pre-About EOF 0x{APPEND_OFF:X}")

def selftest(bak_about, pre_dlgdirs):
    buf = bytearray(open(bak_about, "rb").read())
    apply(buf)
    ref = open(pre_dlgdirs, "rb").read()
    assert len(buf) == len(ref), f"size mismatch 0x{len(buf):X} vs 0x{len(ref):X}"
    if bytes(buf) == ref:
        print("SELFTEST PASS: bak_about + About patch == pre-dlgdirs, byte-for-byte")
    else:
        diffs = [i for i in range(len(ref)) if buf[i] != ref[i]]
        print(f"SELFTEST FAIL: {len(diffs)} differing bytes, first @0x{diffs[0]:X}")
        sys.exit(1)

def main():
    if len(sys.argv) >= 2 and sys.argv[1] == "--selftest":
        selftest(sys.argv[2], sys.argv[3]); return
    target = sys.argv[1] if len(sys.argv) > 1 else "AoWDevX.exe"
    if not os.path.isfile(target):
        sys.exit(f"target not found: {target}")
    buf = bytearray(open(target, "rb").read())
    bak = target + ".bak_about_apply"
    if not os.path.exists(bak):
        shutil.copyfile(target, bak); print(f"backup -> {bak}")
    apply(buf)
    open(target, "wb").write(buf)
    print(f"written: {target}")

if __name__ == "__main__":
    main()
