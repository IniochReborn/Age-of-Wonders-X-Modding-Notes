#   0x43290 8B    TABOUTDLG res entry    BC9E0400 B1080000 -> 00FC0D00 B5080000
#                 (OffsetToData 0x49EBC->0xDFC00, Size 2225->2229)
#   0xDC200 append 2560-byte relocated DFM (RVA 0xDFC00 / VA 0x4DFC00)
#
# Usage:  py editor_about_rebrand_patch.py [path-to-AoWDevX.exe]
# Self-test: py editor_about_rebrand_patch.py --selftest <bak_about> <pre-dlgdirs>
# =============================================================================
