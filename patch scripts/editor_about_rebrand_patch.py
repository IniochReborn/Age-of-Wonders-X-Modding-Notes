#   0x00150 dword SizeOfImage            00000E00 -> 00100E00 (0xE0000->0xE1000)
#   0x0018C dword DataDir[RES].Size      649A0900 -> 00A60900 (0x99A64->0x9A600)
#   0x002C8 dword .rsrc VirtualSize      649A0900 -> 00A60900
